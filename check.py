# check.py
import os
import time
import torch
import torch.nn as nn
import torch.nn.functional as F
import torchvision.transforms as transforms
from torch.utils.data import DataLoader
from torchvision.datasets import ImageFolder
from timm.models.vision_transformer import _cfg  # only needed if you set model.default_cfg

# --- import your model class ---
from imgNet_Sadt import VisRetNet  # requires training script to be guarded with if __name__ == "__main__"

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

# --- ImageNet loaders (val must be 224x) ---
transform_train = transforms.Compose([
    transforms.RandomResizedCrop(224),
    transforms.RandomHorizontalFlip(),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
])

transform_val = transforms.Compose([
    transforms.Resize(256),
    transforms.CenterCrop(224),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
])

train_root = "/2tb/Farid_image_classification/ILSVRC2017_CLS-LOC/ILSVRC/Data/CLS-LOC/train"
val_root   = "/2tb/Farid_image_classification/ILSVRC2017_CLS-LOC/ILSVRC/Data/CLS-LOC/val"

trainset = ImageFolder(root=train_root, transform=transform_train)
valset   = ImageFolder(root=val_root,   transform=transform_val)

trainloader = DataLoader(trainset, batch_size=64, shuffle=True,  num_workers=4, pin_memory=True)
valloader   = DataLoader(valset,   batch_size=64, shuffle=False, num_workers=4, pin_memory=True)

print("Loaded training data:", len(trainset), "classes:", len(trainset.classes))
print("Loaded validation data:", len(valset), "classes:", len(valset.classes))
print("Data loaded")

start = time.time()
for i, (images, labels) in enumerate(trainloader):
    if i == 5: break
print(f"Loaded 5 batches in {time.time() - start:.2f} seconds")

# --- Build the SAME model you train with (for ImageNet-1k: num_classes=1000) ---
model = VisRetNet(
    num_classes=1000,
    embed_dims=[64, 128, 256, 512],
    depths=[2, 2, 8, 2],
    num_heads=[4, 4, 8, 16],
    init_values=[2, 2, 2, 2],
    heads_ranges=[4, 4, 6, 6],
    mlp_ratios=[3, 3, 3, 3],
    drop_path_rate=0.1,
    chunkwise_recurrents=[True, True, False, False],
    layerscales=[False, False, False, False]
).to(device)
# Optional:
# model.default_cfg = _cfg()

print("Model head out_features:", getattr(model.head, "out_features", None))
assert getattr(model.head, "out_features", None) == 1000, "Head must be 1000 for ImageNet-1k"


# --- Quick dataset / model facts ---
print("Train images:", len(trainset))
print("Val images:", len(valset))
print("Train classes:", len(getattr(trainset, "classes", [])))
print("Val classes:", len(getattr(valset, "classes", [])))

# 1) Label spread on VAL
seen = set()
for i, (xb, yb) in enumerate(valloader):
    seen |= set(yb.tolist())
    if i >= 200:
        break
print("VAL label range -> min:", min(seen), "max:", max(seen), "unique labels:", len(seen))

# 2) Shape check
xb, yb = next(iter(valloader))
print("VAL batch shape:", tuple(xb.shape))  # expect (B, 3, 224, 224)

# 3) True VAL metrics (Top-1 / Top-5 / entropy)
model.eval()
tot = 0; corr1 = 0; corr5 = 0; ent_sum = 0.0
with torch.no_grad():
    for xb, yb in valloader:
        xb, yb = xb.to(device), yb.to(device)
        logits = model(xb)
        _, pred1 = logits.topk(1, 1, True, True)
        _, pred5 = logits.topk(5, 1, True, True)
        corr1 += pred1.eq(yb.view(-1, 1)).sum().item()
        corr5 += pred5.eq(yb.view(-1, 1)).sum().item()
        p = torch.softmax(logits, dim=1).clamp_min(1e-12)
        ent_sum += float(-(p * p.log()).sum(dim=1).mean().item()) * xb.size(0)
        tot += xb.size(0)

top1 = 100.0 * corr1 / tot
top5 = 100.0 * corr5 / tot
entropy = ent_sum / tot
print(f"[VAL] Top-1: {top1:.2f}% | Top-5: {top5:.2f}% | Entropy: {entropy:.3f} | N={tot}")
